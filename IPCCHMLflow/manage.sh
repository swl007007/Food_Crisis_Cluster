#!/usr/bin/env bash
# Local IPCCH MLflow server + Cloudflare tunnel:
#   install | uninstall | start | stop | restart | status | tunnel-start | tunnel-stop
# install writes two enabled systemd USER services (~/.config/systemd/user/ipcch-mlflow.service and
# ipcch-cloudflared.service): they start when you open a WSL session (no linger) and restart on failure; they stop
# when WSL shuts down. The units reference only local (non-Dropbox) paths; start/install prepare them first.
# Basic-auth is on (users/passwords in $ROOT/auth/basic_auth.db; admin password set at first start from
# $ROOT/auth/basic_auth.ini). Tunnel config ~/.cloudflared/ipcch-mlflow.yml.
# Without a systemd user bus ("Failed to connect to bus") start/tunnel-start fall back to setsid + pid files.
set -euo pipefail
VENV=/home/swl007007/.venvs/ipcch-mlflow
ROOT=/home/swl007007/.local/share/ipcch-mlflow
UNIT=ipcch-mlflow
TUNNEL_UNIT=ipcch-cloudflared
UNIT_DIR="$HOME/.config/systemd/user"
HOST=127.0.0.1
PORT=5000
PIDFILE="$ROOT/server.pid"
PUBLIC_HOST="${IPCCH_MLFLOW_PUBLIC_HOST:-mlflow.weilunshi.com}"
AUTH_INI="$ROOT/auth/basic_auth.ini"
AUTH_ENV="$ROOT/auth/server.env"          # CSRF secret + read-only "assistant" login for the AI assistant, chmod 600
TUNNEL_CFG="$HOME/.cloudflared/ipcch-mlflow.yml"
TUNNEL_PIDFILE="$ROOT/cloudflared.pid"
CLOUDFLARED="${CLOUDFLARED:-$HOME/.local/bin/cloudflared}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SELF_URL="http://$HOST:$PORT"
export MLFLOW_DISABLE_AGENT_HINT=1 MLFLOW_AUTH_CONFIG_PATH="$AUTH_INI"
SERVER_ARGS=(server
  --backend-store-uri "sqlite:///$ROOT/mlflow.db"
  --artifacts-destination "$ROOT/artifacts" --serve-artifacts
  --app-name basic-auth
  --allowed-hosts "localhost,localhost:*,127.0.0.1,127.0.0.1:*,$PUBLIC_HOST"
  --cors-allowed-origins "http://localhost:$PORT,http://127.0.0.1:$PORT,https://$PUBLIC_HOST"
  --host "$HOST" --port "$PORT" --workers 1)

ensure_auth_config() {   # first start only: random admin password and CSRF key, readable by this user only
  mkdir -p -m 700 "$ROOT/auth"
  if [[ ! -f "$AUTH_ENV" ]]; then
    (umask 077; echo "MLFLOW_FLASK_SERVER_SECRET_KEY=$("$VENV/bin/python" -c 'import secrets; print(secrets.token_hex(32))')" > "$AUTH_ENV")
  fi
  if ! grep -q '^MLFLOW_CRYPTO_KEK_PASSPHRASE=' "$AUTH_ENV"; then   # encrypts AI Gateway secrets in mlflow.db
    (umask 077; echo "MLFLOW_CRYPTO_KEK_PASSPHRASE=$("$VENV/bin/python" -c 'import secrets; print(secrets.token_hex(32))')" >> "$AUTH_ENV")
  fi
  [[ -f "$AUTH_INI" ]] && return 0
  (umask 077; "$VENV/bin/python" - "$AUTH_INI" "$ROOT/auth/basic_auth.db" <<'PY'
import secrets, sys
ini, db = sys.argv[1:3]
open(ini, "w").write(
    "[mlflow]\n"
    "default_permission = READ\n"
    f"database_uri = sqlite:///{db}\n"
    "admin_username = admin\n"
    "# used only when the user store is created (first start); later changes go through MLflow\n"
    f"admin_password = {secrets.token_urlsafe(18)}\n"
    "authorization_function = mlflow.server.auth:authenticate_request_basic_auth\n")
PY
  )
  echo "created $AUTH_INI (admin password inside; chmod 600)"
}
install_assistant_patch() {   # see assistant_patch.py (MLflow 3.17.0 only; no-op unless IPCCH_ASSISTANT_SELF_URL is set)
  local site; site=$("$VENV/bin/python" -c 'import sysconfig; print(sysconfig.get_paths()["purelib"])')
  cp "$HERE/assistant_patch.py" "$site/ipcch_mlflow_assistant_patch.py"
  echo "import ipcch_mlflow_assistant_patch" > "$site/ipcch_mlflow_assistant_patch.pth"
  # read-only catalog lookup used by people and the assistant (see ipcch_model.py)
  printf '#!/bin/sh\nexec "%s" "%s" "$@"\n' "$VENV/bin/python" "$HERE/ipcch_model.py" > "$VENV/bin/ipcch-model"
  chmod 755 "$VENV/bin/ipcch-model"
}
prepare() {
  mkdir -p "$ROOT/artifacts" "$ROOT/logs"
  ensure_auth_config
  install_assistant_patch
}
sd_quote() {   # one systemd Exec argument: plain if safe, else double-quoted; % escaped as %%
  local a="${1//%/%%}"
  if [[ "$a" =~ ^[A-Za-z0-9_./:=,+@-]+$ ]]; then printf '%s' "$a"; else printf '"%s"' "$a"; fi
}
write_units() {   # generated from the variables above; no Dropbox path is used at service start
  local claude_dir path
  claude_dir=$(dirname "$(command -v claude 2>/dev/null || echo /nonexistent/claude)")
  path="$VENV/bin:/usr/local/bin:/usr/bin:/bin"
  [[ -d "$claude_dir" ]] && path="$claude_dir:$path"
  mkdir -p "$UNIT_DIR"
  {
    echo "# generated by IPCCHMLflow/manage.sh install -- edit manage.sh, then rerun install"
    echo "[Unit]"
    echo "Description=IPCCH local MLflow server ($SELF_URL, basic-auth)"
    echo "[Service]"
    echo "Type=simple"
    echo "Environment=MLFLOW_DISABLE_AGENT_HINT=1"
    echo "Environment=MLFLOW_AUTH_CONFIG_PATH=$AUTH_INI"
    echo "Environment=IPCCH_ASSISTANT_SELF_URL=$SELF_URL"
    echo "Environment=PATH=$path"
    echo "EnvironmentFile=$AUTH_ENV"
    printf 'ExecStart=%s' "$VENV/bin/mlflow"; for a in "${SERVER_ARGS[@]}"; do printf ' %s' "$(sd_quote "$a")"; done; echo
    echo "Restart=on-failure"
    echo "RestartSec=10"
    echo "StandardOutput=append:$ROOT/logs/server.log"
    echo "StandardError=append:$ROOT/logs/server.log"
    echo "[Install]"
    echo "WantedBy=default.target"
  } > "$UNIT_DIR/$UNIT.service"
  {
    echo "# generated by IPCCHMLflow/manage.sh install -- edit manage.sh, then rerun install"
    echo "[Unit]"
    echo "Description=Cloudflare tunnel for IPCCH MLflow (https://$PUBLIC_HOST)"
    echo "After=$UNIT.service"
    echo "[Service]"
    echo "Type=simple"
    echo "ExecStart=$CLOUDFLARED tunnel --no-autoupdate --config $TUNNEL_CFG run"
    echo "Restart=on-failure"
    echo "RestartSec=10"
    echo "StandardOutput=append:$ROOT/logs/cloudflared.log"
    echo "StandardError=append:$ROOT/logs/cloudflared.log"
    echo "[Install]"
    echo "WantedBy=default.target"
  } > "$UNIT_DIR/$TUNNEL_UNIT.service"
  systemctl --user daemon-reload
}
units_installed() { [[ -f "$UNIT_DIR/$UNIT.service" && -f "$UNIT_DIR/$TUNNEL_UNIT.service" ]]; }
wait_healthy() {
  for i in $(seq 1 60); do
    if healthy; then echo "running: http://$HOST:$PORT"; return 0; fi
    sleep 1
  done
  echo "server did not become healthy; see $ROOT/logs/server.log" >&2; return 1
}
tunnel_alive() {
  { have_user_bus && systemctl --user is-active --quiet "$TUNNEL_UNIT"; } ||
    { [[ -f "$TUNNEL_PIDFILE" ]] && kill -0 "$(cat "$TUNNEL_PIDFILE")" 2>/dev/null; }
}

have_user_bus() { systemctl --user show-environment >/dev/null 2>&1; }
unit_active() { have_user_bus && systemctl --user is-active --quiet "$UNIT"; }
pid_alive() { [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; }
healthy() { curl -fsS "http://$HOST:$PORT/health" >/dev/null 2>&1; }

case "${1:-status}" in
  install)
    have_user_bus || { echo "no systemd user bus; cannot install services" >&2; exit 1; }
    [[ -f "$TUNNEL_CFG" ]] || { echo "missing $TUNNEL_CFG (see README: Sharing through a Cloudflare tunnel)" >&2; exit 1; }
    prepare
    # replace any earlier transient unit / pid-file processes, then enable both services
    systemctl --user stop "$UNIT" "$TUNNEL_UNIT" 2>/dev/null || true
    if [[ -f "$TUNNEL_PIDFILE" ]]; then kill -TERM "$(cat "$TUNNEL_PIDFILE")" 2>/dev/null || true; rm -f "$TUNNEL_PIDFILE"; fi
    if pid_alive; then kill -TERM -- "-$(cat "$PIDFILE")" 2>/dev/null || true; rm -f "$PIDFILE"; sleep 2; fi
    write_units
    systemctl --user enable --now "$UNIT" "$TUNNEL_UNIT"
    wait_healthy
    echo "installed and enabled: $UNIT, $TUNNEL_UNIT (start with each WSL session)" ;;
  uninstall)
    systemctl --user disable --now "$UNIT" "$TUNNEL_UNIT" 2>/dev/null || true
    rm -f "$UNIT_DIR/$UNIT.service" "$UNIT_DIR/$TUNNEL_UNIT.service"
    systemctl --user daemon-reload
    echo "services removed (store, auth and tunnel config kept)" ;;
  start|restart)
    prepare
    if have_user_bus && units_installed; then
      systemctl --user "$1" "$UNIT"
      wait_healthy; exit $?
    fi
    if unit_active || pid_alive; then echo "already running"; exit 0; fi
    if healthy; then echo "port $PORT already serves /health (unmanaged process?)" >&2; exit 1; fi
    echo "services not installed (run: $0 install); starting as background process (pid file $PIDFILE)"
    set -a; . "$AUTH_ENV"; set +a; export IPCCH_ASSISTANT_SELF_URL="$SELF_URL" PATH="$VENV/bin:$PATH"
    setsid nohup "$VENV/bin/mlflow" "${SERVER_ARGS[@]}" >>"$ROOT/logs/server.log" 2>&1 < /dev/null &
    echo $! > "$PIDFILE"
    wait_healthy ;;
  stop)
    if have_user_bus; then systemctl --user stop "$UNIT" 2>/dev/null || true; fi
    if pid_alive; then
      pid=$(cat "$PIDFILE")
      kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
      for i in $(seq 1 15); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
      kill -KILL -- "-$pid" 2>/dev/null || true
    fi
    rm -f "$PIDFILE"
    echo "stopped (still enabled for the next WSL session; 'uninstall' or 'systemctl --user disable $UNIT' to stop that)" ;;
  status)
    if unit_active; then state="active(systemd)"
    elif pid_alive; then state="active(pid $(cat "$PIDFILE"))"
    else state=inactive; fi
    enabled=n/a
    if have_user_bus; then enabled=$({ systemctl --user is-enabled "$UNIT" "$TUNNEL_UNIT" 2>/dev/null || true; } | paste -sd/ -); fi
    health=$(curl -fsS "http://$HOST:$PORT/health" 2>/dev/null || echo unreachable)
    tunnel=$(tunnel_alive && echo "up(https://$PUBLIC_HOST)" || echo down)
    echo "unit=$UNIT state=$state health=$health url=http://$HOST:$PORT root=$ROOT tunnel=$tunnel autostart(mlflow/tunnel)=$enabled" ;;
  tunnel-start)
    [[ -f "$TUNNEL_CFG" ]] || { echo "missing $TUNNEL_CFG (see README: Sharing through a Cloudflare tunnel)" >&2; exit 1; }
    if tunnel_alive; then echo "tunnel already running"; exit 0; fi
    if have_user_bus && units_installed; then
      systemctl --user start "$TUNNEL_UNIT"
    else
      healthy || { echo "MLflow is not running; start it first" >&2; exit 1; }
      mkdir -p "$ROOT/logs"
      setsid nohup "$CLOUDFLARED" tunnel --no-autoupdate --config "$TUNNEL_CFG" run >>"$ROOT/logs/cloudflared.log" 2>&1 < /dev/null &
      echo $! > "$TUNNEL_PIDFILE"
    fi
    echo "tunnel started: https://$PUBLIC_HOST (log $ROOT/logs/cloudflared.log)" ;;
  tunnel-stop)
    if have_user_bus; then systemctl --user stop "$TUNNEL_UNIT" 2>/dev/null || true; fi
    if [[ -f "$TUNNEL_PIDFILE" ]]; then kill -TERM "$(cat "$TUNNEL_PIDFILE")" 2>/dev/null || true; fi
    rm -f "$TUNNEL_PIDFILE"
    echo "tunnel stopped (still enabled for the next WSL session; 'systemctl --user disable $TUNNEL_UNIT' to stop that)" ;;
  *) echo "usage: $0 install|uninstall|start|stop|restart|status|tunnel-start|tunnel-stop" >&2; exit 2 ;;
esac
